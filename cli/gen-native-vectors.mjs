// Generates the C++ test vectors for the native ML-DSA-44 path in koinos-chain (phase B1).
//
//   node cli/gen-native-vectors.mjs [path/to/koinos-chain/tests/include/koinos/tests/mldsa_vectors.hpp]
//
// Two kinds of vectors:
//   1. "native": deterministic ML-DSA-44 keys from fixed seeds, the address the node must derive from
//      each public key, a fixed 34-byte transaction id, and signatures over it with the native context
//      "koinos/tx/1" (plus one with the contract route's context, which the node must reject).
//   2. The 15 NIST ACVP ML-DSA-44 sigVer vectors from wasm/test/acvp-mldsa44-sigver.json, for the raw
//      verifier (12 of them are must-reject cases).
// Everything is produced by @noble/post-quantum, an implementation independent of the PQ-Crystals code
// the node vendors, so agreement between the two is a real cross-check.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { ml_dsa44 } from "@noble/post-quantum/ml-dsa.js";
import { utils } from "koilib";
import { CONTEXT, CONTEXT_NATIVE, PK_BYTES, SIG_BYTES, NATIVE_ENTRY_BYTES, pqAddress, nativeEntry } from "./lib.mjs";

const out = process.argv[2] || fileURLToPath(new URL("../../koinos-chain/tests/include/koinos/tests/mldsa_vectors.hpp", import.meta.url));
const sha256 = (s) => Uint8Array.from(createHash("sha256").update(s).digest());
const hex = (u8) => Buffer.from(u8).toString("hex");
const zero32 = new Uint8Array(32); // deterministic signing (FIPS 204 rnd = 0) so the file is reproducible

function native(name, seedLabel, txLabel, context) {
  const seed = sha256(seedLabel);
  const { publicKey, secretKey } = ml_dsa44.keygen(seed);
  const txId = Uint8Array.from([0x12, 0x20, ...sha256(txLabel)]);
  const signature = ml_dsa44.sign(txId, secretKey, { context, extraEntropy: zero32 });
  if (!ml_dsa44.verify(signature, txId, publicKey, { context })) throw new Error("self-check failed");
  const address = pqAddress(publicKey);
  const entry = nativeEntry(publicKey, signature);
  if (entry.length !== NATIVE_ENTRY_BYTES) throw new Error("entry size");
  return { name, seed: hex(seed), publicKey: hex(publicKey), address, addressBytes: hex(utils.decodeBase58(address)), txId: hex(txId), context: new TextDecoder().decode(context), signature: hex(signature) };
}

const vectors = [
  native("key_a_native_context", "koinos-pq native vector key A", "koinos-pq native vector tx 1", CONTEXT_NATIVE),
  native("key_b_native_context", "koinos-pq native vector key B", "koinos-pq native vector tx 1", CONTEXT_NATIVE),
  native("key_a_wrong_context", "koinos-pq native vector key A", "koinos-pq native vector tx 1", CONTEXT),
];
// sanity: koilib derives the same kind of address for a secp256k1 key (same function, different key bytes)
const secp = utils.bitcoinAddress(Uint8Array.from(Buffer.from("0279be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798", "hex")));
if (secp !== "1BgGZ9tcN4rm9KBzDn7KprQz87SZ26SAMH") throw new Error("koilib bitcoinAddress does not match the Bitcoin P2PKH reference");

const acvp = JSON.parse(readFileSync(new URL("../wasm/test/acvp-mldsa44-sigver.json", import.meta.url), "utf8"));
for (const t of acvp.tests) {
  if (t.pk.length !== PK_BYTES * 2) throw new Error(`acvp tcId ${t.tcId}: pk length`);
  if (t.signature.length !== SIG_BYTES * 2) throw new Error(`acvp tcId ${t.tcId}: signature length`);
}

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
let h = `#pragma once
// GENERATED by koinos-pq/cli/gen-native-vectors.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// ML-DSA-44 (FIPS 204) test vectors for the native signature path. Produced with @noble/post-quantum
// ${JSON.parse(readFileSync(new URL("../node_modules/@noble/post-quantum/package.json", import.meta.url), "utf8")).version}
// and the NIST ACVP ML-DSA-44 sigVer vectors (${esc(acvp.source)}).

#include <cstdint>
#include <cstddef>

namespace koinos::tests::mldsa {

struct native_vector
{
  const char* name;
  const char* seed_hex;        // 32 byte seed the key pair was derived from (FIPS 204 KeyGen_internal)
  const char* public_key_hex;  // 1312 bytes
  const char* address_base58;  // what a wallet shows
  const char* address_hex;     // 25 bytes: the account bytes the node compares against
  const char* tx_id_hex;       // 34 byte multihash the signature is over
  const char* context;         // FIPS 204 context string used when signing
  const char* signature_hex;   // 2420 bytes
};

inline const native_vector native_vectors[] = {
`;
for (const v of vectors) {
  h += `  { "${v.name}",\n    "${v.seed}",\n    "${v.publicKey}",\n    "${v.address}",\n    "${v.addressBytes}",\n    "${v.txId}",\n    "${esc(v.context)}",\n    "${v.signature}" },\n`;
}
h += `};

struct acvp_vector
{
  int tc_id;
  const char* public_key_hex;
  const char* message_hex;
  const char* context_hex;
  const char* signature_hex;
  bool test_passed; // expected verifier result
  const char* reason;
};

inline const acvp_vector acvp_vectors[] = {
`;
for (const t of acvp.tests) {
  h += `  { ${t.tcId}, "${t.pk.toLowerCase()}", "${(t.message || "").toLowerCase()}", "${(t.context || "").toLowerCase()}", "${t.signature.toLowerCase()}", ${t.testPassed ? "true" : "false"}, "${esc(t.reason || "")}" },\n`;
}
h += `};

} // namespace koinos::tests::mldsa
`;
writeFileSync(out, h);
console.log(`wrote ${out}: ${vectors.length} native vectors, ${acvp.tests.length} ACVP vectors (${acvp.tests.filter((t) => !t.testPassed).length} must-reject)`);
for (const v of vectors) console.log(`  ${v.name}: address ${v.address}`);
